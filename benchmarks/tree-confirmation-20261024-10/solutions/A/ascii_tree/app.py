"""UI state, keyboard actions and a finite, testable terminal event loop."""

from dataclasses import dataclass, field
from pathlib import Path
import time

from .geometry import Tree, generate_tree
from .projection import RenderOptions
from .render import Frame, render_tree

DEFAULT_YAW = 25.0
DEFAULT_PITCH = 8.0


@dataclass
class Explorer:
    seed: int = 42
    mode: str = "3d"
    yaw: float = DEFAULT_YAW
    pitch: float = DEFAULT_PITCH
    angle4: float = 0.0
    zoom: float = 1.0
    aspect: float = 2.0
    time: float = 0.0
    playing: bool = False
    help_open: bool = False
    message: str = "H / ? help   E export   Q quit"
    tree: Tree = field(init=False)
    export_number: int = 0

    def __post_init__(self) -> None:
        self.tree = generate_tree(self.seed)

    def options(self, width: int, height: int) -> RenderOptions:
        return RenderOptions(max(1, min(500, width)), max(1, min(240, height)),
                             self.mode, self.yaw, self.pitch, self.angle4,
                             self.zoom, self.aspect, self.time)

    def frame(self, width: int, height: int) -> Frame:
        return render_tree(self.tree, self.options(width, height))

    def advance(self, seconds: float) -> None:
        if not self.playing or self.help_open:
            return
        self.time += seconds
        if self.mode != "2d":
            self.yaw = (self.yaw + seconds * 12) % 360
        if self.mode == "4d":
            self.angle4 = (self.angle4 + seconds * 16) % 360

    def key(self, key: str) -> str | None:
        """Return an external action (quit/export); mutate only view state otherwise."""
        key = key.lower()
        if key in ("q", "escape", "\x1b"):
            return "quit"
        if key == "\x03":
            raise KeyboardInterrupt
        if key in ("h", "?"):
            self.help_open = not self.help_open
        elif key in ("1", "2", "3"):
            self.mode = {"1": "2d", "2": "3d", "3": "4d"}[key]
        elif key in ("left", "right") and self.mode != "2d":
            self.yaw = (self.yaw + (7 if key == "right" else -7)) % 360
        elif key in ("up", "down") and self.mode != "2d":
            self.pitch = max(-85, min(85, self.pitch + (5 if key == "up" else -5)))
        elif key in ("[", "]") and self.mode == "4d":
            self.angle4 = (self.angle4 + (10 if key == "]" else -10)) % 360
        elif key in ("+", "=", "-"):
            self.zoom = max(0.15, min(5, self.zoom * (1 / 1.12 if key == "-" else 1.12)))
        elif key == " ":
            self.playing = not self.playing
        elif key == "g":
            self.seed += 1
            self.tree = generate_tree(self.seed)
            self.message = f"New tree: seed {self.seed}"
        elif key == "r":
            self.yaw, self.pitch, self.angle4, self.zoom, self.time = DEFAULT_YAW, DEFAULT_PITCH, 0, 1, 0
            self.message = "Orientation, zoom and animation time reset"
        elif key == "e":
            return "export"
        return None

    def export(self, width: int, height: int, directory: Path) -> Path:
        directory.mkdir(parents=True, exist_ok=True)
        # Exclusive creation preserves existing exports across application runs.
        while True:
            self.export_number += 1
            path = directory / f"tree_{self.seed}_{self.mode}_{self.export_number:04d}.txt"
            try:
                with path.open("xb") as output:
                    output.write(self.frame(width, height).bytes())
                self.message = f"Saved {path.name} ({width}x{height})"
                return path
            except FileExistsError:
                continue


