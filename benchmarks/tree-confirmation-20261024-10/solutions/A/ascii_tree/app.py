def viewport_size(width: int, height: int) -> tuple[int, int]:
    height = max(1, min(240, height))
    return max(1, min(500, width)), max(1, height - (1 if height < 7 else 4))


def compose(state: Explorer, width: int, height: int) -> tuple[str, ...]:
    width, height = max(1, min(500, width)), max(1, min(240, height))
    if state.help_open:
        # Keep the close/quit hint visible even in very small terminals.
        content = list(HELP[:max(0, height - 1)]) + ["H close help | Q / Esc quit"]
    elif height < 7:
        content = [f"{state.mode.upper()} seed {state.seed} | H help Q quit"]
        content += list(state.frame(width, max(1, height - 1)).rows)
    else:
        status = "PLAY" if state.playing else "PAUSED"
        title = f"ASCII TREE EXPLORER | {state.mode.upper()} | seed {state.seed} | {status}"
        menu = "1 2D   2 3D   3 4D   Arrows orbit   [ ] XW   + - zoom   Space play"
        canvas = state.frame(*viewport_size(width, height))
        if state.mode == "4d":
            footer = f"4D DATA -> 3D -> SCREEN | XW {state.angle4:5.1f} deg | W = growth distance"
        elif state.mode == "3d":
            footer = f"Yaw {state.yaw:5.1f}  Pitch {state.pitch:5.1f}  Zoom {state.zoom:.2f} | Z-buffer"
        else:
            footer = f"XY orthographic | Zoom {state.zoom:.2f} | Same procedural graph"
        content = [title, menu, *canvas.rows, footer, state.message]
    return tuple((content[index] if index < len(content) else "")[:width].ljust(width)
                 for index in range(height))


def run_loop(state: Explorer, terminal, export_dir: Path = Path("exports"),
             fps: float = 12, duration: float | None = None) -> int:
    """The terminal is injected so resize, input and shutdown can be tested offline."""
    start = last_tick = time.monotonic()
    next_frame = start
    previous_size = None
    dirty = True
    with terminal:
        while True:
            now = time.monotonic()
            if duration is not None and now - start >= duration:
                return 0
            size = terminal.size()
            if size != previous_size:
                dirty, previous_size = True, size
            if state.playing and not state.help_open:
                if now >= next_frame:
                    state.advance(min(now - last_tick, 0.25))
                    last_tick = now
                    dirty = True
            else:
                last_tick = now
            if dirty and now >= next_frame:
                terminal.draw(compose(state, *size))
                dirty = False
                next_frame = now + 1 / fps
            key = terminal.read_key(0.02)
            if key is None:
                continue
            action = state.key(key)
            dirty = True
            # User input is immediate; only animation is rate limited.
            next_frame = 0
            if action == "quit":
                return 0
            if action == "export":
                try:
                    state.export(*viewport_size(*size), export_dir)
                except OSError as error:
                    state.message = f"Export failed: {error.strerror or str(error)}"
